"""One-GPU stages for the fixed-policy critic comparison."""
from collections import Counter
from pathlib import Path
import time

import torch

from .fixed_policy import items, answer, output, ROOT, read, sha256, write_json
from .value_audit import stable_seed
from .value_audit_gpu import Generator, grade, cached_samples, last_prefix_value


def generate(out,m,task):
    if not 0<=task<m['shards']:raise ValueError('Invalid generation shard')
    generator=Generator(Path(m['actor_path']),m)
    from slice_critic.config import completion_prompt
    groups={}
    for row in items(out,m):groups.setdefault(row['id'],[]).append(row)
    for group in list(groups.values())[task::m['shards']]:
        row=group[0]
        if all((out/'answers'/f'{r["key"]}.json').exists() for r in group):
            for r in group:answer(out,r)
            continue
        prompt=generator.tokenizer.encode(completion_prompt(row['question']),add_special_tokens=False)
        if not 0<len(prompt)<=512:raise ValueError('Overlong/empty prompt')
        seed=stable_seed(m['seed'],'rollout-group',row['id'])
        ident=dict(manifest_sha256=sha256(out/'manifest.json'),question_id=row['id'],
                   count=len(group),seed=seed,kind='shared-fitting-or-bank-rollout')
        saved=cached_samples(out/'rollout-groups'/f'{stable_seed(row["id"])}.json',ident,
            lambda:grade(generator,row['ground_truth'],generator.generate(prompt,len(group),m['response_cap'],seed),[]))
        for row,generated in zip(group,saved['samples'],strict=True):
            write_json(out/'answers'/f'{row["key"]}.json',dict(generated,key=row['key'],question_id=row['id'],split=row['split'],
                                prompt_ids=prompt,manifest_sha256=sha256(out/'manifest.json'),seed=seed))
        print(f'Generated {row["id"]}: {row["split"]}, {len(group)} answers',flush=True)


@torch.inference_mode()
def extract(out,m,task):
    if not 0<=task<m['shards']:raise ValueError('Invalid extraction shard')
    from transformers import AutoModel
    from slice_critic.inference import load_filter
    from slice_critic.layers import sampled_block_states,layer_spec
    from slice_critic.features import rms_coordinates
    from slice_critic.chunks import token_chunks
    from .value_audit_gpu import load_tokenizer
    from .fixed_policy import features
    torch.backends.cuda.matmul.allow_tf32=False;torch.backends.cudnn.allow_tf32=False
    torch.set_float32_matmul_precision('highest')
    tokenizer=load_tokenizer(Path(m['actor_path']))
    model=AutoModel.from_pretrained(ROOT/'models/qwen-math',local_files_only=True,trust_remote_code=False,
        torch_dtype=torch.float32,attn_implementation='eager').to('cuda').eval().requires_grad_(False)
    compressor,mean,scale=load_filter(out/'sparse.pt',m['filter_sha256'],layers=m['layers'],
                                    eps=m['rms_eps'],model_path=ROOT/'models/qwen-math')
    compressor=compressor.to('cuda')
    raw_layer=layer_spec(len(model.layers))['two_thirds']-1
    layers=list(dict.fromkeys(m['layers']+[raw_layer]))
    for row in items(out,m)[task::m['shards']]:
        path=out/'features'/f'{row["key"]}.pt'
        if path.exists() and path.with_suffix('.json').exists():features(out,row);continue
        data=answer(out,row);tokens=data['token_ids'];prompt=data['prompt_ids']
        ids=torch.tensor([prompt+tokens],device='cuda')
        captured=sampled_block_states(model,ids,len(prompt),len(tokens),list(range(len(tokens))),layers)
        x=torch.cat([rms_coordinates(captured[l].float(),m['rms_eps']) for l in m['layers']],1)
        z=torch.cat([compressor.features(((block-mean)/scale).to('cuda')).cpu() for block in x.split(256)])
        rms=rms_coordinates(captured[raw_layer].float(),model.config.rms_norm_eps)
        plan=token_chunks(tokenizer,tokens,'math',32)
        if z.shape!=(len(tokens),768) or not torch.isfinite(z).all() or not torch.isfinite(rms).all():
            raise ValueError('Invalid frozen features')
        path.parent.mkdir(exist_ok=True)
        temporary=path.with_suffix('.tmp')
        torch.save(dict(slice=z,rms=rms,starts=list(plan.starts),fallback_reason=plan.fallback_reason),temporary)
        temporary.replace(path)
        write_json(path.with_suffix('.json'),dict(manifest_sha256=sha256(out/'manifest.json'),
            answer_sha256=sha256(out/'answers'/f'{row["key"]}.json'),sha256=sha256(path)))


@torch.inference_mode()
def predict(out,m,task):
    if task==5:return  # Independent GRPO prompt groups are generated by MC shard 0.
    if task!=4:raise ValueError('Only transformer/GRPO use this prediction adapter')
    from transformers import AutoModelForTokenClassification
    from slice_critic.storage import model_identity
    identity=read(out/'neural.json')
    if identity['model_identity']!=model_identity(out/'transformer'):
        raise ValueError('Transformer critic changed')
    model,info=AutoModelForTokenClassification.from_pretrained(out/'transformer',local_files_only=True,
        trust_remote_code=False,torch_dtype=torch.bfloat16,attn_implementation='sdpa',output_loading_info=True)
    if info['missing_keys'] or info['unexpected_keys'] or info.get('mismatched_keys'):
        raise ValueError('Incomplete transformer restore')
    model=model.to('cuda').eval().requires_grad_(False)
    rows=[dict(state_id=s['state_id'],prediction=last_prefix_value(model,s['prompt_ids'],s['prefix_ids']))
          for s in read(out/'bank.json')['states']]
    write_json(out/'predictions-transformer.json',output(out,rows))


def mc(out,m,task):
    if not 0<=task<m['shards']:raise ValueError('Invalid reference shard')
    bank=read(out/'bank.json')['states'];generator=Generator(Path(m['actor_path']),m)
    header=dict(manifest_sha256=sha256(out/'manifest.json'),bank_sha256=sha256(out/'bank.json'))
    if task==0:
        questions={s['question_id']:s for s in bank};baseline={}
        for q,s in questions.items():
            seed=stable_seed(m['seed'],'independent-grpo',q)
            ident=dict(header,question_id=q,count=4,seed=seed,kind='grpo-baseline')
            saved=cached_samples(out/'continuations'/f'group-{stable_seed(q)}.json',ident,
                lambda:grade(generator,s['ground_truth'],generator.generate(s['prompt_ids'],4,m['response_cap'],seed),[]))
            baseline[q]=sum(r['score'] for r in saved['samples'])/4
        write_json(out/'predictions-grpo.json',output(out,[dict(state_id=s['state_id'],prediction=baseline[s['question_id']]) for s in bank]))
    rows=[];statuses=Counter();tokens=0;capped=0;seconds=0.;started=time.perf_counter()
    for s in bank[task::m['shards']]:
        samples=[]
        for offset in range(0,m['recipe']['samples'],m['reference_batch']):
            count=min(m['reference_batch'],m['recipe']['samples']-offset)
            seed=stable_seed(m['seed'],'common-reference',s['state_id'],offset)
            ident=dict(header,state_id=s['state_id'],count=count,offset=offset,seed=seed,kind='shared-reference')
            saved=cached_samples(out/'continuations'/f'state-{stable_seed(s["state_id"])}-{offset}.json',ident,
                lambda:grade(generator,s['ground_truth'],generator.generate(s['prompt_ids']+s['prefix_ids'],count,s['remaining_tokens'],seed),s['prefix_ids']))
            samples.extend(saved['samples']);seconds+=saved['seconds']
        statuses.update(r['verifier_status'] for r in samples)
        tokens+=sum(len(r['token_ids']) for r in samples);capped+=sum(r['capped'] for r in samples)
        rows.append(dict(state_id=s['state_id'],samples=len(samples),successes=sum(r['score'] for r in samples)))
        print(f'Shared references: shard {task}, {len(rows)} states complete',flush=True)
    write_json(out/f'reference-{task}.json',output(out,rows,label_statuses=dict(statuses),
        response_tokens=tokens,capped=capped,seconds=time.perf_counter()-started,cached_sample_seconds=seconds))
